"""Noise parameters handed to a filter, and how to derive the *matched* ones from the simulator.

A "matched" filter knows exactly the simulator's process noise Q, initial covariance P0 and
GNSS covariance R, and models the IMU's white noise (not its bias, random walk or scale error,
which are the unmodelled errors a real filter would also face).

IMU white noise enters through the input: ``f(x, u_imu) ~ f(x, u) + G n`` with
``n ~ N(0, Qu)``, so the effective process covariance is ``Q + G Qu G^T`` (``G = df/du``).
"""

from __future__ import annotations

from dataclasses import dataclass, replace

import numpy as np

from afkn.sim import motion
from afkn.sim.config import SimConfig
from afkn.sim.sensors import DeviceParams


@dataclass(frozen=True, eq=False)
class FilterParams:
    """Everything a filter needs besides the data.

    ``R`` and ``Qu`` are either a single matrix (shared) or one matrix per trajectory ``(N, d, d)``
    (needed for mixed-profile sets such as the global-test and trusted sets).
    """

    Q: np.ndarray  # (4, 4) additive process covariance per step
    R: np.ndarray  # (2, 2) or (N, 2, 2) GNSS covariance
    Qu: np.ndarray  # (2, 2) or (N, 2, 2) IMU white-noise covariance [yaw rate, accel]
    P0: np.ndarray  # (4, 4) initial covariance
    model: str = "ctrv"
    dt: float = 0.1

    def __post_init__(self) -> None:
        if self.model not in motion.MODELS:
            raise ValueError(f"unknown motion model '{self.model}'")
        if self.Q.shape != (4, 4) or self.P0.shape != (4, 4):
            raise ValueError("Q and P0 must be 4x4")
        for name, m in (("R", self.R), ("Qu", self.Qu)):
            if m.shape[-2:] != (2, 2) or m.ndim not in (2, 3):
                raise ValueError(f"{name} must have shape (2,2) or (N,2,2), got {m.shape}")

    def scaled(self, q: float = 1.0, r: float = 1.0, qu: float | None = None) -> "FilterParams":
        """Deliberately mismatched copy: Q*q, R*r (Qu*q unless ``qu`` given). Used for mismatch experiments."""
        return replace(self, Q=self.Q * q, R=self.R * r, Qu=self.Qu * (q if qu is None else qu))


def matched_params(cfg: SimConfig, device: DeviceParams) -> FilterParams:
    """Matched parameters for data generated by one device (a client's splits)."""
    return FilterParams(
        Q=cfg.Q(),
        R=device.R(),
        Qu=np.diag(np.square(device.imu_sigma)),
        P0=cfg.P0(),
        model=cfg.motion_model,
        dt=cfg.dt,
    )


def matched_params_by_profile(cfg: SimConfig, profile_idx: np.ndarray) -> FilterParams:
    """Matched parameters for a mixed set (global test / trusted): per-trajectory R and Qu by profile.

    Mixed sets use ``sigma_scale = 1``, so each profile's configured sigmas are exact.
    """
    names = cfg.profile_names
    R_by = np.stack([cfg.profiles[n].gnss.sigma ** 2 * np.eye(2) for n in names])
    Qu_by = np.stack([np.diag([cfg.profiles[n].imu.sigma_yaw ** 2, cfg.profiles[n].imu.sigma_acc ** 2]) for n in names])
    idx = np.asarray(profile_idx, dtype=int)
    return FilterParams(Q=cfg.Q(), R=R_by[idx], Qu=Qu_by[idx], P0=cfg.P0(), model=cfg.motion_model, dt=cfg.dt)
